def _build_data_root_suffix(data_root: str) -> str | None:
    root = Path(data_root)
    parts = [p for p in root.parts if p not in {"/", "\\", ""}]
    if len(parts) >= 2:
        return f"{parts[-2]}_{parts[-1]}"
    if len(parts) == 1:
        return parts[-1]
    return None


def _load_saved_pose_se3(exp_space: Sandbox) -> torch.Tensor:
    for filename in ("poses.csv", "poses.npy"):
        pose_path = exp_space.path(filename)
        if not pose_path.exists():
            continue
        if pose_path.suffix == ".csv":
            data = np.loadtxt(pose_path, delimiter=",", skiprows=1, dtype=float)
        else:
            data = np.load(pose_path)
        if data.ndim == 1:
            data = data.reshape(1, -1)
        return torch.tensor(data[:, 1:])
    raise FileNotFoundError(f"No poses.csv or poses.npy found under {exp_space.folder}")


def VisualizeRerunCallback(frame: StereoFrame, system: MACVO, pb: ColoredTqdm):
    rr_plt.set_time_sequence("frame_idx", frame.frame_idx)

    # Non-key frame does not need visualization
    if system.graph.frames.data["need_interp"][-1]: return

    if frame.frame_idx > 0:
        rr_plt.log_trajectory("/world/est", pp.SE3(system.graph.frames.data["pose"].tensor))

    rr_plt.log_camera("/world/macvo/cam_left", pp.SE3(system.graph.frames.data["pose"][-1]), system.graph.frames.data["K"][-1])
    rr_plt.log_image ("/world/macvo/cam_left", frame.stereo.imageL[0].permute(1, 2, 0))

    map_points = system.graph.get_frame2map(system.graph.frames[-1:])
    rr_plt.log_points("/world/point_cloud", map_points.data["pos_Tw"], map_points.data["color"], map_points.data["cov_Tw"], "sphere")

    vo_points  = system.graph.get_match2point(system.graph.get_frame2match(system.graph.frames[-1:]))
    rr_plt.log_points("/world/vo_tracking", vo_points.data["pos_Tw"], vo_points.data["color"], vo_points.data["cov_Tw"], "sphere")


def VisualizeIMUData(frame: StereoFrame, system: MACVO):
    if (not hasattr(frame, "imu")) or (getattr(frame, "imu") is None):
        return

    imu = frame.imu
    if imu.time_ns.numel() == 0:
        return

    imu_time_ns = imu.time_ns.reshape(-1).detach().cpu().long()
    imu_acc = imu.acc.reshape(-1, 3).detach().cpu().float()
    imu_gyro = imu.gyro.reshape(-1, 3).detach().cpu().float()

    # Log tri-axis IMU as time-series lines under two groups: /imu/acc/* and /imu/gyro/*
    for i in range(imu_time_ns.numel()):
        rr_plt.set_time_sequence("imu_ns", int(imu_time_ns[i].item()))
        rr_plt.log_scalar("/imu/acc/x", float(imu_acc[i, 0].item()))
        rr_plt.log_scalar("/imu/acc/y", float(imu_acc[i, 1].item()))
        rr_plt.log_scalar("/imu/acc/z", float(imu_acc[i, 2].item()))
        rr_plt.log_scalar("/imu/gyro/x", float(imu_gyro[i, 0].item()))
        rr_plt.log_scalar("/imu/gyro/y", float(imu_gyro[i, 1].item()))
        rr_plt.log_scalar("/imu/gyro/z", float(imu_gyro[i, 2].item()))


def VisualizeVRAMUsage(frame: StereoFrame, system: MACVO, pb: ColoredTqdm):
    if torch.cuda.is_available():
        allocated_memory = torch.cuda.memory_reserved(0) / 1e9  # Convert to GB
        allocated_memory = f"{round(allocated_memory, 3)} GB"
    else:
        allocated_memory = "N/A"

    pb.set_description(desc=f"{system.graph}, VRAM={allocated_memory}")

