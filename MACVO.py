def _apply_optimizer_cli_overrides(args, odomcfg_dict: dict) -> None:
    optimizer_args = odomcfg_dict["optimizer"]["args"]
    if args.imu_factor_mode is not None:
        optimizer_args["imu_factor_mode"] = args.imu_factor_mode
    if args.local_ba_window_size is not None:
        if int(args.local_ba_window_size) < 3:
            raise ValueError("--local-ba-window-size must be >= 3")
        optimizer_args["local_ba_window_size"] = int(args.local_ba_window_size)
    if args.local_ba_writeback is not None:
        optimizer_args["local_ba_writeback"] = str(args.local_ba_writeback)
    if bool(args.local_ba_free_first_frame):
        optimizer_args["local_ba_fix_first_frame"] = False


def _apply_visual_cache_cli_overrides(args, odomcfg_dict: dict) -> None:
    mode = str(getattr(args, "visual_cache_mode", "off")).strip().lower()
    cache_path = getattr(args, "visual_cache_path", None)
    if mode == "off":
        if cache_path is not None:
            raise ValueError("--visual-cache-path requires --visual-cache-mode replay")
        return
    if mode != "replay":
        raise ValueError(f"unsupported visual cache mode: {mode!r}")
    if cache_path is None:
        raise ValueError("--visual-cache-path is required when --visual-cache-mode replay")

    odomcfg_dict["args"]["visual_cache_mode"] = "replay"
    odomcfg_dict["args"]["visual_cache_path"] = str(Path(cache_path))
    odomcfg_dict["frontend"] = {"type": "ReplayFrontend", "args": {}}


def _resolve_scene_name(datacfg) -> str:
    configured = getattr(datacfg.args, "scene", None)
    if isinstance(configured, str) and configured.strip():
        return configured.strip()
    return Path(str(datacfg.args.root)).name


def _build_run_readme(project_name, args, odomcfg, datacfg) -> str:
    using_imu_data = "imu" in str(datacfg.type).lower()
    motion_model = str(odomcfg.motion.type)
    optimizer = str(odomcfg.optimizer.type)
    frontend = str(odomcfg.frontend.type)

    steps = [
        "1. Load stereo (and optionally IMU) sequence from config.",
        f"2. Run frontend: {frontend} for depth/matching estimation.",
        f"3. Use motion prior: {motion_model}.",
        f"4. Run backend optimizer: {optimizer}.",
        "5. Save trajectory/map outputs and runtime artifacts.",
    ]

    if using_imu_data:
        steps.insert(3, "4. Consume IMU packet(s) for frame-to-frame motion initialization.")

    if args.useRR:
        steps.append("6. Stream visualization to Rerun and save rerun.rrd.")

    if args.live_display:
        steps.append("6. Serve a read-only browser dashboard with IMU-center MACVO raw, VIO committed, and GT states.")

    if args.saveplt:
        steps.append("7. Save matplotlib visual diagnostics.")

    lines = [
        f"# Run Summary: {project_name}",
        "",
        "## Runtime Arguments",
        f"- odom config: {args.odom}",
        f"- data config: {args.data}",
        f"- seq_from: {args.seq_from}",
        f"- seq_to: {args.seq_to}",
        f"- preload: {args.preload}",
        f"- useRR: {args.useRR}",
        f"- saveplt: {args.saveplt}",
        f"- timing: {args.timing}",
        "",
        "## Active Modules",
        f"- data type: {datacfg.type}",
        f"- frontend: {frontend}",
        f"- motion model: {motion_model}",
        f"- optimizer: {optimizer}",
        f"- outlier filter: {odomcfg.outlier.type}",
        "",
        "## Improvement Steps Executed",
    ]
    lines.extend([f"- {s}" for s in steps])

    return "\n".join(lines) + "\n"


